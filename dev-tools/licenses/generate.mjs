// Regenerates the dependency licence lists shown in Settings → About and
// shipped in the installers:
//   src/assets/licenses/rust.txt  (cargo-about over src-tauri/Cargo.lock)
//   src/assets/licenses/npm.txt   (only the npm packages that end up in the
//                                  frontend bundle, found by a throwaway build)
// Usage: node dev-tools/licenses/generate.mjs   (needs `cargo install cargo-about`)
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const out = join(root, "src/assets/licenses");
const here = join(root, "dev-tools/licenses");

function rust() {
  const text = execFileSync(
    "cargo",
    ["about", "generate", "--locked", "--config", join(here, "about.toml"), join(here, "about.hbs")],
    { cwd: join(root, "src-tauri"), encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] },
  );
  writeFileSync(join(out, "rust.txt"), text.trimEnd() + "\n");
}

/** Package directory (…/node_modules/<name> or …/node_modules/@scope/<name>) of a module id. */
function packageDir(id) {
  const marker = `${sep}node_modules${sep}`;
  const i = id.lastIndexOf(marker);
  if (i < 0) return null;
  const rest = id.slice(i + marker.length).split(sep);
  const depth = rest[0].startsWith("@") ? 2 : 1;
  return id.slice(0, i + marker.length) + rest.slice(0, depth).join(sep);
}

async function bundledPackages() {
  const dirs = new Set();
  const tmp = mkdtempSync(join(tmpdir(), "sahne-licenses-"));
  try {
    await build({
      root,
      logLevel: "warn",
      build: { outDir: tmp, emptyOutDir: true, write: false },
      plugins: [
        {
          name: "collect-packages",
          generateBundle(_, bundle) {
            for (const chunk of Object.values(bundle)) {
              if (chunk.type !== "chunk") continue;
              for (const id of Object.keys(chunk.modules)) {
                const dir = packageDir(id.replace(/\?.*$/, "").replace(/^\0/, ""));
                if (dir) dirs.add(dir);
              }
            }
          },
        },
      ],
    });
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
  return [...dirs];
}

function licenceText(dir) {
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$|-)/i.test(f));
  return file ? readFileSync(join(dir, file), "utf8").trim() : null;
}

async function npm() {
  // The About view imports npm.txt itself, so the throwaway build needs one.
  if (!existsSync(join(out, "npm.txt"))) writeFileSync(join(out, "npm.txt"), "");
  const pkgs = (await bundledPackages())
    .filter((dir) => existsSync(join(dir, "package.json")))
    .map((dir) => ({ dir, meta: JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) }))
    .sort((a, b) => a.meta.name.localeCompare(b.meta.name));
  let text =
    "npm packages bundled into Sahne's frontend.\n" +
    "Generated by dev-tools/licenses/generate.mjs; do not edit by hand.\n";
  for (const { dir, meta } of pkgs) {
    const repo = typeof meta.repository === "string" ? meta.repository : meta.repository?.url;
    text += `\n${"=".repeat(80)}\n${meta.name} ${meta.version} (${meta.license ?? "unknown licence"})\n`;
    if (repo) text += `${repo.replace(/^git\+/, "")}\n`;
    text += `${"-".repeat(80)}\n\n${licenceText(dir) ?? "No licence file in the package; see its licence field above."}\n`;
  }
  writeFileSync(join(out, "npm.txt"), text);
  return pkgs.map((p) => `${p.meta.name}@${p.meta.version}`);
}

rust();
console.log("npm packages in the bundle:", (await npm()).join(", "));
